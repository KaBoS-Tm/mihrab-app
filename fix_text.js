// دالة تطبيع النص القرآني لضمان اتصال حرف اللام وهمزة الوصل والتشكيل على كافة المتصفحات
function normalizeQuranText(rawText) {
  if (!rawText) return '';
  return rawText
    // تصحيح همزة الوصل المصحفية لتتصل باللام مباشرة بدون تفكك
    .replace(/\u0671/g, 'ا')
    // إزالة رموز الضبط الزائدة التي تسبب مربعات غير معروفة في أندرويد
    .replace(/[\u06D6-\u06DC\u06DF-\u06E8\u06EA-\u06ED]/g, '')
    // ضبط المسافات حول علامات التنوين المشوهة
    .trim();
}
